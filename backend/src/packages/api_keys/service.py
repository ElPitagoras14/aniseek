import secrets

from loguru import logger

from database.client import engine
from exceptions import NotFoundError
from packages.auth import hash_secret_token

from . import repository

# Fixed marker so a key is recognizable in a config file or a secret scanner
# (design D2). The stored prefix is the marker plus 8 characters.
KEY_MARKER = "ask_"
PREFIX_LENGTH = len(KEY_MARKER) + 8


async def get_own_api_key_controller(current_user: dict) -> dict | None:
    async with engine.connect() as conn:
        return await repository.get_api_key(conn, current_user["id"])


async def generate_api_key_controller(current_user: dict) -> dict:
    key = KEY_MARKER + secrets.token_urlsafe(32)
    prefix = key[:PREFIX_LENGTH]
    async with engine.begin() as conn:
        row = await repository.upsert_api_key(
            conn, current_user["id"], prefix, hash_secret_token(key)
        )
    logger.info(f"API key {prefix}… generated by {current_user['username']}")
    # The only time the full key is ever returned.
    return {"key": key, "prefix": row["prefix"], "created_at": row["created_at"]}


async def revoke_api_key_controller(actor: dict, user_id: str) -> None:
    async with engine.begin() as conn:
        deleted = await repository.delete_api_key(conn, user_id)
    if not deleted:
        raise NotFoundError("API key not found")
    logger.info(f"API key of user {user_id} revoked by {actor['username']}")


async def list_api_keys_controller() -> dict:
    async with engine.connect() as conn:
        rows = await repository.list_api_keys(conn)
    items = [{**row, "user_id": str(row["user_id"])} for row in rows]
    return {"items": items, "total": len(items)}
